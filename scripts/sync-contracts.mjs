#!/usr/bin/env node
// Build-time only. The application imports the generated strings, never fs.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const directory = fileURLToPath(new URL("../src/contracts/", import.meta.url));
const output = path.join(directory, "markdown.generated.ts");
const args = process.argv.slice(2);
if (args.some((arg) => arg !== "--check")) {
  throw new Error("Usage: node scripts/sync-contracts.mjs [--check]");
}
const entries = readdirSync(directory)
  .filter((name) => name.endsWith(".md"))
  .sort()
  .map((name) => {
    if (!/^[a-z]{3}-v[0-9.]+-\d{4}-\d{2}\.md$/.test(name)) {
      throw new Error(`Invalid contract filename: ${name}`);
    }
    const bytes = readFileSync(path.join(directory, name));
    const text = bytes.toString("utf8");
    if (!Buffer.from(text, "utf8").equals(bytes)) {
      throw new Error(`Contract must be valid UTF-8: ${name}`);
    }
    return [name.slice(0, -3), text];
  });
if (!entries.length) throw new Error("No contract sources found");
const generated =
  "// Generated by npm run contracts:sync. Do not edit; Markdown files are authoritative.\n" +
  "// Deliberately no timestamps or newline/Unicode normalisation: contract bytes are immutable.\n" +
  `export const CONTRACT_MARKDOWN: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(Object.fromEntries(entries), null, 2)});\n`;

if (args.includes("--check")) {
  let existing;
  try { existing = readFileSync(output, "utf8"); } catch { /* reported below */ }
  if (existing !== generated) {
    console.error("Contract bundle is stale. Run npm run contracts:sync and review the generated diff.");
    process.exitCode = 1;
  } else {
    console.log(`Contract bundle matches all ${entries.length} Markdown sources.`);
  }
} else {
  writeFileSync(output, generated);
  console.log(`Bundled ${entries.length} contract versions without changing source bytes.`);
}
