/**
 * SpecialCarer — DSAR data map.
 *
 * One entry per table in the public schema, recording what the subject
 * access export does with it. This is the written decision the exporter
 * is held to: `exported` tables must be read by `exportSubject`, and
 * every other table needs a stated reason.
 *
 * A guard test (`data-map.test.ts`) fails when:
 *   - a table is created in `supabase/migrations` without an entry here;
 *   - an `exported` entry is not read by the exporter (or the reverse);
 *   - a table that is not exported has no reason.
 *
 * Dispositions
 *   exported     the exporter reads it (see the reason for any part withheld)
 *   deferred     holds personal data but needs a decision before release
 *   excluded     personal data deliberately not released, with the reason
 *   not_personal configuration or aggregate data about no individual
 *
 * Staff notes about the subject (admin_notes and similar) are currently
 * withheld from every exported table. That follows the earlier exporter
 * design and needs a legal view; it is listed in docs/dsar-data-map.md.
 */
